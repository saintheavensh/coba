import { DBContext } from "../../../shared/types/db-context";
import { PurchaseOrder } from "./entities/purchase.entity";

export interface IPurchaseRepository {
    findById(id: string, dbOrTx?: DBContext): Promise<PurchaseOrder | null>;
    save(purchase: PurchaseOrder, dbOrTx?: DBContext): Promise<void>;
    findAll(filters?: any, dbOrTx?: DBContext): Promise<PurchaseOrder[]>;
    delete(id: string, dbOrTx?: DBContext): Promise<void>;
}

export interface IPurchasePaymentRepository {
    savePayment(payment: any, dbOrTx?: DBContext): Promise<void>;
    findPaymentsByPurchaseId(purchaseId: string, dbOrTx?: DBContext): Promise<any[]>;
}

export interface IActivityLogger {
    log(entry: {
        userId: string;
        action: string;
        entityType: string;
        entityId: string;
        description: string;
    }, dbOrTx?: DBContext): Promise<void>;
}

export interface INotificationGateway {
    notifyPurchaseOrderCreated(
        payload: { purchaseId: string; userId: string; supplierId: string },
        dbOrTx?: DBContext
    ): Promise<void>;

    notifyGoodsReceived(
        payload: { purchaseId: string; userId: string; hasDiscrepancy: boolean },
        dbOrTx?: DBContext
    ): Promise<void>;
}

export interface IPurchaseVariantPolicyGateway {
    ensureVariantAllowedForSupplier(
        params: { productId: string; variantName: string; supplierId: string },
        dbOrTx?: DBContext
    ): Promise<void>;
}

export interface IAccountingGateway {
    createJournal(params: {
        description: string;
        referenceType: string;
        referenceId: string;
        lines: { accountId: string; debit: number; credit: number; description?: string }[];
        isAutoGenerated?: boolean;
    }, userId?: string, dbOrTx?: DBContext): Promise<string>;
}
